// Builds the horse and jockey mask sprites from the traced Muybridge frames.
// Source: Eadweard Muybridge, "The Horse in Motion" (1878), public domain.
// Usage: npm run sprites
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const source = JSON.parse(readFileSync(new URL('scripts/data/muybridge-gallop.json', root), 'utf8'))
const outDir = new URL('src/features/horses/assets/', root)

const [, , width, height] = source.viewBox.split(/\s+/).map(Number)
const frameCount = source.paths.length

const svg = (body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width * frameCount} ${height}">${body}</svg>\n`

const horse = source.paths
  .map((d, i) => `<path transform="translate(${width * i} 0)" d="${d}"/>`)
  .join('')

// The jockey is the horse frame clipped to the rider: same pixels, so both layers stay in sync.
const jockey = source.paths
  .map((d, i) => {
    const [x, y, w, h] = source.jockey[i]
    return (
      `<g transform="translate(${width * i} 0)">` +
      `<clipPath id="j${i}"><rect x="${x}" y="${y}" width="${w}" height="${h}"/></clipPath>` +
      `<path clip-path="url(#j${i})" d="${d}"/></g>`
    )
  })
  .join('')

writeFileSync(new URL('gallop-horse.svg', outDir), svg(horse))
writeFileSync(new URL('gallop-jockey.svg', outDir), svg(jockey))
writeFileSync(
  new URL('gallop.meta.ts', outDir),
  `// Generated by scripts/build-gallop-sprites.mjs. Do not edit.\n` +
    `export const GALLOP_FRAME_COUNT = ${frameCount}\n` +
    `export const GALLOP_ASPECT_RATIO = ${(width / height).toFixed(4)}\n`,
)

console.log(`Wrote ${frameCount}-frame sprites to ${fileURLToPath(outDir)}`)
